<#
.SYNOPSIS
  Builds BM64Recompiled on Windows from a retail ROM, fetching missing tools.

.DESCRIPTION
  Steps (each skipped when its output already exists, unless -Regen/-Reconfigure):
    1. Portable LLVM 19.1.3 (MIPS-capable clang + ld.lld for patches/) into the toolchain dir.
    2. N64Recomp + RSPRecomp at the commit CI uses, built with the VS developer environment.
    3. bm64.decomp.us.z64 generated from the retail ROM (tools/re/make_decomp_rom.py).
    4. RecompiledFuncs/ and rsp/aspMain.cpp generated by N64Recomp / RSPRecomp.
    5. CMake configure (Ninja, VS clang-cl) and build of the BM64Recompiled target.

  Requires: Visual Studio 2022+ with "Desktop development with C++" and "C++ Clang tools",
  CMake, Python 3 with `rabbitizer`, git, and the retail ROM (env BM64_ROM or -Rom).

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File tools\build-windows.ps1
  powershell -ExecutionPolicy Bypass -File tools\build-windows.ps1 -Config Debug -BuildDir build-debug
#>
param(
    [string]$Config = "RelWithDebInfo",
    [string]$BuildDir = "build",
    [string]$Toolchain = "",
    [string]$Rom = "",
    [switch]$Regen,
    [switch]$Reconfigure
)

$ErrorActionPreference = "Stop"
$Repo = (Resolve-Path (Join-Path $PSScriptRoot "..")).Path
if (-not $Toolchain) { $Toolchain = Join-Path (Split-Path $Repo -Parent) "toolchain" }
New-Item -ItemType Directory -Force $Toolchain | Out-Null
if ($Rom) { $env:BM64_ROM = $Rom }

$LlvmVersion = "19.1.3"
$N64RecompCommit = "98bf104b1b5ed83126af8bcab0cc964782617dbf"

function Step($msg) { Write-Host "==> $msg" -ForegroundColor Cyan }

function Import-VsEnv {
    $vswhere = "${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer\vswhere.exe"
    $vs = & $vswhere -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
    if (-not $vs) { throw "Visual Studio with C++ tools not found" }
    $vcvars = Join-Path $vs "VC\Auxiliary\Build\vcvars64.bat"
    cmd /c "`"$vcvars`" >nul && set" | ForEach-Object {
        if ($_ -match '^([^=]+)=(.*)$') { Set-Item -Path "env:$($matches[1])" -Value $matches[2] }
    }
    $ninja = Join-Path $vs "Common7\IDE\CommonExtensions\Microsoft\CMake\Ninja"
    if (Test-Path $ninja) { $env:PATH = "$ninja;$env:PATH" }
    if (-not (Get-Command clang-cl -ErrorAction SilentlyContinue)) { throw "clang-cl not found; install the 'C++ Clang tools' VS component" }
    if (-not (Get-Command ninja -ErrorAction SilentlyContinue)) { throw "ninja not found" }
}

function Invoke-Checked([string]$exe, [string[]]$arguments) {
    & $exe @arguments
    if ($LASTEXITCODE -ne 0) { throw "$exe failed with exit code $LASTEXITCODE" }
}

Import-VsEnv

# 1. Portable LLVM for the MIPS patches
$Llvm = Join-Path $Toolchain "LLVM-$LlvmVersion-Windows-X64\bin"
if (-not (Test-Path (Join-Path $Llvm "clang.exe"))) {
    Step "Downloading portable LLVM $LlvmVersion"
    $archive = Join-Path $Toolchain "LLVM.tar.xz"
    $ProgressPreference = "SilentlyContinue"
    Invoke-WebRequest -Uri "https://github.com/llvm/llvm-project/releases/download/llvmorg-$LlvmVersion/LLVM-$LlvmVersion-Windows-X64.tar.xz" -OutFile $archive
    Push-Location $Toolchain; try { Invoke-Checked tar @("-xf", $archive) } finally { Pop-Location }
    Remove-Item $archive
}

# 2. N64Recomp / RSPRecomp
$RecompSrc = Join-Path $Toolchain "N64RecompSource"
$RecompBin = Join-Path $RecompSrc "cmake-build"
if (-not (Test-Path (Join-Path $RecompBin "N64Recomp.exe")) -or -not (Test-Path (Join-Path $RecompBin "RSPRecomp.exe"))) {
    Step "Building N64Recomp $N64RecompCommit"
    if (-not (Test-Path $RecompSrc)) { Invoke-Checked git @("clone", "https://github.com/Mr-Wiseguy/N64Recomp.git", $RecompSrc) }
    Invoke-Checked git @("-C", $RecompSrc, "checkout", $N64RecompCommit)
    Invoke-Checked git @("-C", $RecompSrc, "submodule", "update", "--init", "--recursive")
    Invoke-Checked cmake @("-S", $RecompSrc, "-B", $RecompBin, "-G", "Ninja", "-DCMAKE_BUILD_TYPE=Release")
    Invoke-Checked cmake @("--build", $RecompBin, "--target", "N64RecompCLI", "RSPRecomp")
}
Copy-Item (Join-Path $RecompBin "N64Recomp.exe"), (Join-Path $RecompBin "RSPRecomp.exe") $Repo -Force

Push-Location $Repo
try {
    if (-not (Test-Path "BM64Syms\dump.toml")) {
        Step "Initialising submodules"
        Invoke-Checked git @("submodule", "update", "--init", "--recursive")
    }

    # 3. Decomp-layout ROM
    if ($Regen -or -not (Test-Path "bm64.decomp.us.z64")) {
        Step "Generating bm64.decomp.us.z64 from the retail ROM"
        Invoke-Checked python @("tools\re\make_decomp_rom.py", (Join-Path $Repo "bm64.decomp.us.z64"))
    }

    # 4. Recompiled C
    if ($Regen -or -not (Test-Path "RecompiledFuncs\recomp_overlays.inl") -or -not (Test-Path "rsp\aspMain.cpp")) {
        Step "Running N64Recomp and RSPRecomp"
        Invoke-Checked ".\N64Recomp.exe" @("bm64.us.toml")
        Invoke-Checked ".\RSPRecomp.exe" @("aspMain.toml")
    }

    # 5. Configure and build
    if ($Reconfigure -and (Test-Path $BuildDir)) { Remove-Item -Recurse -Force $BuildDir }
    if (-not (Test-Path (Join-Path $BuildDir "CMakeCache.txt"))) {
        Step "Configuring $BuildDir ($Config)"
        $clangVer = (& clang-cl --version | Select-Object -First 1) -replace '.*version (\d+).*', '$1'
        $cflags = ""
        # SDL 2.26's SDL_endian.h redefines _m_prefetch, which clang 20+ provides as a builtin.
        if ([int]$clangVer -ge 20) { $cflags = "-D__PRFCHWINTRIN_H" }
        Invoke-Checked cmake @("-S", ".", "-B", $BuildDir, "-G", "Ninja", "-DCMAKE_BUILD_TYPE=$Config",
            "-DCMAKE_C_COMPILER=clang-cl", "-DCMAKE_CXX_COMPILER=clang-cl",
            "-DPATCHES_C_COMPILER=$Llvm\clang.exe", "-DPATCHES_LD=$Llvm\ld.lld.exe",
            "-DCMAKE_C_FLAGS=$cflags", "-DCMAKE_CXX_FLAGS=$cflags -Xclang -fexceptions -Xclang -fcxx-exceptions")
    }
    Step "Building BM64Recompiled"
    Invoke-Checked cmake @("--build", $BuildDir, "--target", "BM64Recompiled")
    Step "Done: $(Join-Path $Repo $BuildDir)\BM64Recompiled.exe"
}
finally { Pop-Location }
